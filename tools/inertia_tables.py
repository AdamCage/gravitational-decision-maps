"""Generate the manuscript's inertia tables from the verified study summaries."""

from argparse import ArgumentParser
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
METHODS = ("static", "inertial", "clipped_inertial", "relativistic")
STAGES = {"synthetic": "Synthetic", "public": "Public"}
FAMILIES = {"affine_shells": "Affine shells", "wavy_shells": "Wavy shells", "open_chains": "Open chains",
            "local_lobes": "Separated lobes", "pendigits": "PenDigits", "seeds": "Seeds"}
NAMES = dict(zip(METHODS, ("Static", "Classical", "Hard cap", "Relativistic"), strict=True))


def _row(*cells):
    return " & ".join(cells) + r" \\"


def _table(name, columns, headings, rows):
    return [rf"\newcommand{{\{name}}}{{%", rf"\begin{{tabular}}{{{columns}}}", r"\toprule",
            _row(*headings), r"\midrule", *rows, r"\bottomrule", r"\end{tabular}%", "}"]


def generate(results):
    accuracy, timing = [], []
    for stage, label in STAGES.items():
        summary = json.loads((results / f"relativistic_{stage}" / "summary.json").read_bytes())
        if summary["stage"] != stage or summary["phase"] != "final":
            raise ValueError("The manuscript requires final study summaries")
        primary = summary["primary"]
        for family, profile in summary["families"].items():
            accuracy.append(_row(FAMILIES[family], *(f"{100 * profile[m]['balanced_accuracy']:.2f}" for m in METHODS)))
        accuracy.append(_row(rf"\textbf{{{label} mean}}",
                             *(f"{100 * primary[m]['balanced_accuracy']:.2f}" for m in METHODS)))
        for method in METHODS:
            values = primary[method]
            timing.append(_row(label if method == METHODS[0] else "", NAMES[method],
                               f"{values['median_batch_ms']:.3f}", f"{values['median_us_per_query']:.3f}",
                               f"{values['median_latency_ratio']:.2f}",
                               f"{values['refinement_disagreements']:,}",
                               f"{values['static_flips']:,}"))
        if stage != "public":
            accuracy.append(r"\midrule")
            timing.append(r"\midrule")
    lines = ["% Generated by tools/inertia_tables.py from the verified study summaries.",
             *_table("InertiaAccuracyTable", "lrrrr", ("Cohort", *NAMES.values()), accuracy),
             *_table("InertiaTimingTable", "llrrrrr", ("Cohort", "Method", "ms/batch", r"$\mu$s/query",
                                                         r"$\times$ static", "Refinement", "Flips"), timing)]
    return ("\n".join(lines) + "\n").encode()


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=ROOT / "relativistic_results")
    parser.add_argument("--output", type=Path, default=ROOT / "paper" / "relativistic_results.tex")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate(args.results)
    if args.check:
        if args.output.read_bytes() != content:
            parser.error("The manuscript tables differ from the verified summaries")
    else:
        args.output.write_bytes(content)


if __name__ == "__main__":
    main()
